def normalize_theme(theme_name):
    return theme_name if theme_name in THEME_PALETTES else "dark"


def theme_palette(theme_name):
    return THEME_PALETTES[normalize_theme(theme_name)]


def theme_texture_path(theme_name):
    filename = THEME_TEXTURES.get(normalize_theme(theme_name))
    if not filename:
        return None
    path = RESOURCE_DIR / "assets" / "themes" / filename
    return path if path.exists() else None
